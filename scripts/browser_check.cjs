async function selectPassage(page, first, start, last = first, end = start + 6) {
  await page.evaluate(({ first, start, last, end }) => {
    const paragraphs = document.querySelectorAll('[data-item-text]')
    const locate = (element, offset) => {
      const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT)
      let node
      while ((node = walker.nextNode())) {
        if (offset <= node.textContent.length) return [node, offset]
        offset -= node.textContent.length
      }
      throw new Error('Selection offset not found')
    }
    const [a, b] = locate(paragraphs[first], start), [c, d] = locate(paragraphs[last], end)
    const range = document.createRange(); range.setStart(a, b); range.setEnd(c, d)
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range)
  }, { first, start, last, end })
  await page.getByRole('toolbar', { name: 'Selected passage tools' }).waitFor()
}
